// Courses added, edited or hidden by the admin. Applied from the copy kept on this phone, then refreshed in the background.
(function () {
  var K = 'lawlink-cedits';
  function apply(items) {
    (items || []).forEach(function (e) {
      var i = -1, k;
      for (k = 0; k < COURSES.length; k++) if (COURSES[k].id === e.id) { i = k; break; }
      if (e.hidden) { if (i > -1) COURSES.splice(i, 1); return; }
      var c = { id: e.id, name: e.name, group: e.group || 'General', level: 0, cle: e.cle || 0, aliases: e.aliases || [], parts: e.parts || [] };
      if (i > -1) COURSES[i] = c; else COURSES.push(c);
    });
  }
  var cache = null;
  try { cache = JSON.parse(localStorage.getItem(K)); } catch (e) { cache = null; }
  if (cache && cache.items) apply(cache.items);
  window.refreshCourses = function (force) {
    return fetch('/api', { method: 'POST', headers: { 'Content-Type': 'text/plain;charset=utf-8' }, body: JSON.stringify({ action: 'courses.list' }) })
      .then(function (r) { return r.json(); })
      .then(function (o) {
        if (!o || !o.ok) return;
        var old = cache ? cache.v : 0;
        try { localStorage.setItem(K, JSON.stringify({ v: o.data.v, items: o.data.items })); } catch (e) {}
        if (o.data.v !== old || force) {
          var ae = document.activeElement, busy = ae && /^(INPUT|TEXTAREA|SELECT)$/.test(ae.tagName);
          var seen = ''; try { seen = sessionStorage.getItem('lawlink-creload'); } catch (e) {}
          if (!busy && seen !== String(o.data.v)) { try { sessionStorage.setItem('lawlink-creload', String(o.data.v)); } catch (e) {} location.reload(); }
        }
      }).catch(function () {});
  };
  if (!/login\.html|settings\.html/.test(location.pathname)) setTimeout(function () { window.refreshCourses(false); }, 400);
})();
